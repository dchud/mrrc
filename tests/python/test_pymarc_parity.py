def _field_text_variants(case):
    """Build one field shape in pymarc and in each mrrc form that carries
    field text: the wrapper Field (detached, and as a live handle from a
    record) and, for data fields, the native Field that AuthorityRecord
    and HoldingsRecord return."""
    pymarc = pytest.importorskip("pymarc")
    tag, content = case
    if isinstance(content, str):
        theirs = pymarc.Field(tag=tag, data=content)
        detached = mrrc.Field(tag, data=content)
        native = None
    else:
        theirs = pymarc.Field(
            tag=tag,
            indicators=pymarc.Indicators(" ", "0"),
            subfields=[pymarc.Subfield(c, v) for c, v in content],
        )
        detached = mrrc.Field(
            tag,
            " ",
            "0",
            subfields=[mrrc.Subfield(c, v) for c, v in content],
        )
        native = mrrc._mrrc.Field(
            tag,
            " ",
            "0",
            subfields=[mrrc.Subfield(c, v) for c, v in content],
        )
    record = mrrc.Record()
    record.add_field(detached)
    handle = record[tag]
    return theirs, detached, handle, native


@pytest.mark.parametrize(
    "case", _FIELD_TEXT_CASES.values(), ids=_FIELD_TEXT_CASES.keys()
)
@pytest.mark.parametrize("method", ["value", "format_field"])
def test_field_text_matches_pymarc(case, method) -> None:
    """value() and format_field() give pymarc's text for every field
    shape, from the wrapper Field, a live handle, and the native Field."""
    theirs, detached, handle, native = _field_text_variants(case)
    expected = getattr(theirs, method)()
    assert getattr(detached, method)() == expected
    assert getattr(handle, method)() == expected
    if native is not None:
        assert getattr(native, method)() == expected


@pytest.mark.parametrize(
    "case", _FIELD_TEXT_CASES.values(), ids=_FIELD_TEXT_CASES.keys()
)
def test_field_str_matches_pymarc(case) -> None:
    """str(field) gives pymarc's MARCMaker line for every field shape."""
    theirs, detached, handle, _ = _field_text_variants(case)
    assert str(detached) == str(theirs)
    assert str(handle) == str(theirs)


def test_field_text_whitespace_matches_pymarc() -> None:
    """value() and format_field() strip exactly the characters pymarc's
    str.strip() does, for every whitespace character and a few that are
    not whitespace."""
    pymarc = pytest.importorskip("pymarc")
    candidates = [chr(c) for c in range(0x3001) if chr(c).isspace()]
    candidates += ["᠎", "​", "﻿", "x"]
    mismatched = []
    for ch in candidates:
        subfields = [("a", f"{ch}A{ch}"), ("x", f"{ch}X{ch}")]
        theirs = pymarc.Field(
            tag="650",
            indicators=pymarc.Indicators(" ", "0"),
            subfields=[pymarc.Subfield(c, v) for c, v in subfields],
        )
        ours = mrrc.Field(
            "650",
            " ",
            "0",
            subfields=[mrrc.Subfield(c, v) for c, v in subfields],
        )
        if (ours.value(), ours.format_field()) != (
            theirs.value(),
            theirs.format_field(),
        ):
            mismatched.append(hex(ord(ch)))
    assert mismatched == []


@pytest.mark.parametrize(
    "codes", [("a",), ("a", "b"), ("b", "a"), ("ab",), ("",), ()]
)
def test_get_subfields_matches_pymarc(codes) -> None:
    """get_subfields() returns values in field order, whatever the order
    of the codes, and a multi-character code matches nothing."""
    pymarc = pytest.importorskip("pymarc")
    subfields = [("a", "1"), ("b", "2"), ("a", "3"), ("c", "4")]
    theirs = pymarc.Field(
        tag="245",
        indicators=pymarc.Indicators("1", "0"),
        subfields=[pymarc.Subfield(c, v) for c, v in subfields],
    )
    ours = mrrc.Field(
        "245", "1", "0", subfields=[mrrc.Subfield(c, v) for c, v in subfields]
    )
    assert ours.get_subfields(*codes) == theirs.get_subfields(*codes)


def test_setitem_keeps_subfield_position_like_pymarc() -> None:
    """field[code] = value replaces the subfield where it is, so the
    field's text and serialization match pymarc after the edit."""
    pymarc = pytest.importorskip("pymarc")
    subfields = [("a", "Old title :"), ("b", "sub /"), ("c", "A.")]
    theirs = pymarc.Field(
        tag="245",
        indicators=pymarc.Indicators("1", "0"),
        subfields=[pymarc.Subfield(c, v) for c, v in subfields],
    )
    record = mrrc.Record()
    record.add_field(
        mrrc.Field(
            "245",
            "1",
            "0",
            subfields=[mrrc.Subfield(c, v) for c, v in subfields],
        )
    )
    theirs["a"] = "New title :"
    record["245"]["a"] = "New title :"
    ours = record["245"]
    assert str(ours) == str(theirs)
    assert ours.as_marc() == theirs.as_marc("utf-8")


def test_permissive_iteration_shape_matches_pymarc() -> None:
    """mrrc(permissive=True) and pymarc(permissive=True) yield the same
    record-vs-None shape over a 100-record, 10%-malformed corpus."""
    pymarc = pytest.importorskip("pymarc")

    stream, expected = _build_corpus()

    mrrc_shape = [
        r is not None for r in mrrc.MARCReader(stream, permissive=True)
    ]
    pymarc_shape = [
        r is not None
        for r in pymarc.MARCReader(io.BytesIO(stream), permissive=True)
    ]

    assert len(mrrc_shape) == _TOTAL, (
        f"mrrc iterated {len(mrrc_shape)}, expected {_TOTAL}"
    )
    assert len(pymarc_shape) == _TOTAL, (
        f"pymarc iterated {len(pymarc_shape)}, expected {_TOTAL}"
    )
    # Both match the intended shape, and therefore each other.
    assert mrrc_shape == expected, (
        "mrrc shape diverged from the corpus pattern"
    )
    assert pymarc_shape == expected, (
        "pymarc shape diverged from the corpus pattern"
    )
    assert mrrc_shape == pymarc_shape


_LEADER = "00714cjm a2200205 i 4500"


def _leader_property_names(leader_class) -> list[str]:
    return sorted(
        name
        for name, value in vars(leader_class).items()
        if isinstance(value, property)
    )


def test_leader_exposes_every_pymarc_property() -> None:
    """Every property on pymarc's Leader exists on mrrc's Leader."""
    pymarc = pytest.importorskip("pymarc")
    leader = mrrc.Leader(_LEADER)
    missing = [
        name
        for name in _leader_property_names(pymarc.Leader)
        if not hasattr(leader, name)
    ]
    assert missing == []


def test_leader_pymarc_properties_read_the_same_positions() -> None:
    """pymarc's Leader property names read the same leader positions.

    mrrc returns the numeric positions (record length, indicator and
    subfield code counts, base address) as ints where pymarc returns
    zero-padded strings, so values are compared in pymarc's string form.
    """
    pymarc = pytest.importorskip("pymarc")
    ours, theirs = mrrc.Leader(_LEADER), pymarc.Leader(_LEADER)
    mismatched = {}
    for name in _leader_property_names(pymarc.Leader):
        expected = getattr(theirs, name)
        actual = str(getattr(ours, name, None)).zfill(len(expected))
        if actual != expected:
            mismatched[name] = (actual, expected)
    assert mismatched == {}


def test_leader_pymarc_properties_write_the_same_positions() -> None:
    """Setting a single-character position through pymarc's property name
    changes the same byte of the leader in both libraries."""
    pymarc = pytest.importorskip("pymarc")
    mismatched = {}
    for name in _leader_property_names(pymarc.Leader):
        if len(getattr(pymarc.Leader(_LEADER), name)) != 1:
            continue
        ours, theirs = mrrc.Leader(_LEADER), pymarc.Leader(_LEADER)
        if not isinstance(getattr(ours, name, ""), str):
            continue  # numeric positions are ints in mrrc
        try:
            setattr(ours, name, "z")
        except AttributeError as e:
            mismatched[name] = repr(e)
            continue
        setattr(theirs, name, "z")
        if str(ours) != str(theirs):
            mismatched[name] = (str(ours), str(theirs))
    assert mismatched == {}


# MARC-8 designation escapes for each character set, keyed by final byte.
# Sets keyed in the low half are designated as G0, ANSEL and the extended
# sets as G1; ESC ) E and then ESC s restore the defaults afterwards. (That
# order matters for pymarc 5.3.1, which reads the byte after ESC s as a
# character, so an escape sequence right after ESC s is not recognised.)
_MARC8_DESIGNATIONS = {
    0x42: b"\x1b(B",
    0x45: b"\x1b)E",
    0x32: b"\x1b(2",
    0x33: b"\x1b(3",
    0x34: b"\x1b)4",
    0x4E: b"\x1b(N",
    0x51: b"\x1b)Q",
    0x53: b"\x1b(S",
    0x62: b"\x1bb",
    0x67: b"\x1bg",
    0x70: b"\x1bp",
    0x31: b"\x1b$1",
}
_MARC8_RESET = b"\x1b)E\x1bs"


def _marc8_values(codesets) -> list[tuple[int, bytes]]:
    """(final byte, MARC-8 value) pairs covering every mapping in every
    character set. A combining mark is followed by a base character from
    the same set (or ASCII 'a' when G0 is still Basic Latin), and EACC is
    split into values that fit an ISO 2709 field."""
    values = []
    for final, table in sorted(codesets.items()):
        multibyte = final == 0x31
        g1 = not multibyte and min(table) >= 0x80
        if g1 or final == 0x42:
            base = b"a"
        else:
            first = min(
                k for k, (_, comb) in table.items() if not comb and k > 0x20
            )
            base = first.to_bytes(3 if multibyte else 1, "big")
        chars = []
        for key, (_, combining) in sorted(table.items()):
            if key < 0x20 or 0x7F <= key < 0xA0:
                continue  # controls: not graphic characters
            code = key.to_bytes(3, "big") if multibyte else bytes([key])
            chars.append(code + (base if combining else b""))
        chunk = 900 if multibyte else len(chars)
        for i in range(0, len(chars), chunk):
            body = b"".join(chars[i : i + chunk])
            values.append(
                (final, _MARC8_DESIGNATIONS[final] + body + _MARC8_RESET)
            )
    return values


def test_marc8_decoding_matches_pymarc_for_every_mapping() -> None:
    """Every character in every MARC-8 character set, read from a record
    whose leader says MARC-8, decodes to the same text in mrrc and pymarc."""
    pymarc = pytest.importorskip("pymarc")
    from pymarc import marc8_mapping

    mismatched = []
    for final, value in _marc8_values(marc8_mapping.CODESETS):
        field = b"10\x1fa" + value + b"\x1e"
        directory = b"245" + b"%04d%05d" % (len(field), 0) + b"\x1e"
        base = 24 + len(directory)
        total = base + len(field) + 1
        leader = b"%05dnam  22%05d   4500" % (total, base)
        data = leader + directory + field + b"\x1d"
        (ours,) = list(mrrc.MARCReader(data))
        (theirs,) = list(pymarc.MARCReader(io.BytesIO(data)))
        if ours["245"]["a"] != theirs["245"]["a"]:
            mismatched.append(hex(final))
    assert mismatched == []


@pytest.mark.parametrize("handling", ["strict", "replace", "ignore"])
def test_invalid_utf8_matches_pymarc(handling) -> None:
    """For a record whose leader says UTF-8 and whose 245$a holds an
    invalid byte, each utf8_handling value gives pymarc's result: strict
    rejects the record (pymarc yields None; mrrc does under
    permissive=True, its pymarc-shaped mode), replace and ignore decode
    the same text."""
    pymarc = pytest.importorskip("pymarc")
    field = b"10\x1faCaf\xffe\x1e"
    directory = b"245" + b"%04d%05d" % (len(field), 0) + b"\x1e"
    base = 24 + len(directory)
    leader = b"%05dnam a22%05d   4500" % (base + len(field) + 1, base)
    data = leader + directory + field + b"\x1d"

    (ours,) = list(
        mrrc.MARCReader(data, permissive=True, utf8_handling=handling)
    )
    (theirs,) = list(
        pymarc.MARCReader(io.BytesIO(data), utf8_handling=handling)
    )
    if theirs is None:
        assert ours is None
    else:
        assert ours["245"]["a"] == theirs["245"]["a"]
